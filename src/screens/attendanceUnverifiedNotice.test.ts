import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

/**
 * ラチェット: 出席画面の「CLASSで確認してください」告知の現在の姿を検査する。
 *
 * ⚠ 成功カードの注意（「※CLASSの出欠に反映されているか必ずご確認ください。」）は残す。消す時は必ず裁定を取ること。
 *
 * 出席の自動送信は間欠的に登録されない事象を追ってきた経路で、アプリが「出席を登録しました」と
 * 出しても実際には登録されていないことがある。成功カードの注意が黙って消えると、利用者が食い違いに
 * 気づく手段が無くなる＝意味が反転する。vitest は純粋ロジック層しか実行できないので、
 * rawColorGuard.test.ts と同じくソースを読む形で保全する。
 *
 * 2026-09-24 本人裁定: 製品版として公開する更新で、画面上部の常設告知「出席の自動登録は試験段階です。
 * 登録できたかは必ずCLASSでご確認ください。」を撤去する（成功カードの注意は残す）。撤去した後は、
 * 古い枝のマージなどで無言のうちに復活しないよう、不在を固定する。復活させる時は本人の裁定を取り、
 * このテストの該当ケースを反転すること。
 *
 * ⚠ (A) は「この表示は登録の成功を保証しません」等の一律の否定文を含めない裁定済み。
 *   outcome='ok' には attended（CLASSページの実測）と result.ok（応答一致・誤検出実績あり）の
 *   2経路があり、一律の否定は前者で過剰なため。経路ごとの出し分けも却下済み。復活させない。
 */
const src = readFileSync(join(__dirname, 'AttendanceScreen.tsx'), 'utf8')

describe('出席画面の未検証告知（ラチェット）', () => {
  it('成功カードに「CLASSの出欠に反映されているか」の注意が在る', () => {
    expect(src).toContain('※CLASSの出欠に反映されているか必ずご確認ください。')
  })

  it('画面上部の常設「試験段階です」の告知は撤去済み（2026-09-24 裁定・製品版）', () => {
    expect(src).not.toContain('出席の自動登録は試験段階です')
  })
})
